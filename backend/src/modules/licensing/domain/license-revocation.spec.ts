import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import {
  createHash,
  createPrivateKey,
  createPublicKey,
  sign as cryptoSign,
} from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { toTrustedKeys } from './license-document.js';
import {
  canonicalizeRevocation,
  decodeRevocationTransport,
  parseRevocationDocument,
  RevocationDocumentError,
  type RevocationPayload,
} from './license-revocation.js';

/**
 * `VREV1` — the signed revocation artifact (OD-LIC-17, protocol
 * `docs/licensing/revocation-artifact-protocol.md`).
 *
 * Evidence discipline is the same as the license vector suite: the expected
 * canonical bytes are a LITERAL in this file (never produced by the production
 * canonicalizer at test time), and the oracle for signatures/digests is
 * node:crypto over the committed fixture bytes. The committed vector directory
 * `docs/licensing/vectors/revocation/` is generated by
 * `src/tools/generate-licensing-vectors.ts` and is byte-diffed by CI.
 */

const VECTORS = join(process.cwd(), '..', 'docs', 'licensing', 'vectors');
const REVOCATION_VECTORS = join(VECTORS, 'revocation');

function loadJson(dir: string, file: string): any {
  return JSON.parse(readFileSync(join(dir, file), 'utf8'));
}

function vector(id: string): any {
  const file = readdirSync(REVOCATION_VECTORS)
    .filter((name) => name.endsWith('.json'))
    .find((name) => loadJson(REVOCATION_VECTORS, name).id === id);
  if (file === undefined) throw new Error(`Missing revocation vector ${id}`);
  return loadJson(REVOCATION_VECTORS, file);
}

function keyFixture(name: string): any {
  return loadJson(join(VECTORS, 'keys'), `${name}.json`);
}

function trusted(...names: string[]) {
  return toTrustedKeys(
    names.map((name) => {
      const fixture = keyFixture(name);
      return {
        id: fixture.keyId as string,
        key: createPublicKey({
          key: Buffer.from(fixture.publicKeySpkiBase64, 'base64'),
          format: 'der',
          type: 'spki',
        }),
      };
    }),
  );
}

const AUTHORITY_A = keyFixture('authority-a');
const AUTHORITY_B = keyFixture('authority-b');
const TRUST_A = trusted('authority-a');

/**
 * The literal canonical bytes of `REV-CAN-01`. Written out by hand, field by
 * field, in the protocol's order — this is the cross-runtime oracle: an
 * implementation in any language must produce exactly this string.
 */
const CAN_01_LITERAL =
  '{"v":1,"kind":"SERVER_LICENSE_REVOCATION","revocationId":"01TESTREVOCATION0000000000",' +
  '"licenseId":"01TESTLICENSE0000000000000","targetOperationId":"01TESTOPERATION00000000000",' +
  '"customerId":"01TESTCUSTOMER000000000000","customerCode":"CUST-TEST-01",' +
  '"installationId":"01TESTINSTALLATION000000000","effect":"LICENSE_ONLY",' +
  '"reason":"CONTRACT_TERMINATION","reasonDetail":"Contract 2026-114 ended on 2026-10-20.",' +
  '"issuerKeyId":"' +
  AUTHORITY_A.keyId +
  '","issuedAt":"2026-10-20T09:30:00.000Z"}';

const CAN_02_LITERAL =
  '{"v":1,"kind":"SERVER_LICENSE_REVOCATION","revocationId":"01TESTREVOCATION0000000001",' +
  '"licenseId":"01TESTLICENSE0000000000000","targetOperationId":"01TESTOPERATION00000000000",' +
  '"customerId":"01TESTCUSTOMER000000000000","customerCode":"CUST-TEST-01",' +
  '"installationId":"01TESTINSTALLATION000000000","effect":"LICENSE_ONLY",' +
  '"reason":"NON_PAYMENT","reasonDetail":null,"issuerKeyId":"' +
  AUTHORITY_A.keyId +
  '","issuedAt":"2026-10-20T09:31:00.000Z"}';

function payload(
  overrides: Partial<RevocationPayload> = {},
): RevocationPayload {
  return {
    v: 1,
    kind: 'SERVER_LICENSE_REVOCATION',
    revocationId: '01TESTREVOCATION0000000000',
    licenseId: '01TESTLICENSE0000000000000',
    targetOperationId: '01TESTOPERATION00000000000',
    customerId: '01TESTCUSTOMER000000000000',
    customerCode: 'CUST-TEST-01',
    installationId: '01TESTINSTALLATION000000000',
    effect: 'LICENSE_ONLY',
    reason: 'CONTRACT_TERMINATION',
    reasonDetail: 'Contract 2026-114 ended on 2026-10-20.',
    issuerKeyId: AUTHORITY_A.keyId,
    issuedAt: new Date('2026-10-20T09:30:00.000Z'),
    ...overrides,
  };
}

function sign(
  value: RevocationPayload,
  privateKeyBase64: string = AUTHORITY_A.privateKeyPkcs8Base64,
  options: { body?: string } = {},
): string {
  const body = Buffer.from(
    options.body ?? canonicalizeRevocation(value),
    'utf8',
  );
  const key = createPrivateKeyFrom(privateKeyBase64);
  return [
    'VREV1',
    body.toString('base64url'),
    cryptoSign(null, body, key).toString('base64url'),
  ].join('.');
}

function createPrivateKeyFrom(base64: string) {
  return createPrivateKey({
    key: Buffer.from(base64, 'base64'),
    format: 'der',
    type: 'pkcs8',
  });
}

function rejectionOf(run: () => unknown): RevocationDocumentError {
  try {
    run();
  } catch (error) {
    if (error instanceof RevocationDocumentError) return error;
    throw error;
  }
  throw new Error('expected a RevocationDocumentError');
}

describe('VREV1 canonical bytes (cross-runtime literals)', () => {
  it('serializes exactly the committed literal, field for field', () => {
    expect(canonicalizeRevocation(payload())).toBe(CAN_01_LITERAL);
    expect(vector('REV-CAN-01').expectedCanonicalUtf8).toBe(CAN_01_LITERAL);
    expect(
      Buffer.from(
        vector('REV-CAN-01').expectedCanonicalUtf8Hex,
        'hex',
      ).toString('utf8'),
    ).toBe(CAN_01_LITERAL);
  });

  it('emits an explicit null, never an omitted field', () => {
    const nullDetail = payload({
      revocationId: '01TESTREVOCATION0000000001',
      reason: 'NON_PAYMENT',
      reasonDetail: null,
      issuedAt: new Date('2026-10-20T09:31:00.000Z'),
    });
    expect(canonicalizeRevocation(nullDetail)).toBe(CAN_02_LITERAL);
    expect(canonicalizeRevocation(nullDetail)).toContain('"reasonDetail":null');
    expect(vector('REV-CAN-02').expectedCanonicalUtf8).toBe(CAN_02_LITERAL);
  });

  it('is domain-separated from the license contract', () => {
    const bytes = canonicalizeRevocation(payload());
    expect(bytes.startsWith('{"v":1,"kind":"SERVER_LICENSE_REVOCATION"')).toBe(
      true,
    );
    // A license payload is never producible here, and vice versa.
    expect(bytes).not.toContain('SERVER_LICENSE_VERSION');
  });
});

describe('VREV1 verification', () => {
  it('verifies the committed valid artifact and reproduces its digest', () => {
    const ok = vector('REV-OK-01');
    const verified = parseRevocationDocument(ok.artifact, TRUST_A);
    expect(verified.keyId).toBe(AUTHORITY_A.keyId);
    expect(verified.payload).toMatchObject({
      revocationId: '01TESTREVOCATION0000000000',
      licenseId: '01TESTLICENSE0000000000000',
      targetOperationId: '01TESTOPERATION00000000000',
      effect: 'LICENSE_ONLY',
      reason: 'CONTRACT_TERMINATION',
      issuerKeyId: AUTHORITY_A.keyId,
    });
    const body = Buffer.from(ok.expectedCanonicalUtf8Hex, 'hex');
    expect(verified.canonicalBody).toBe(CAN_01_LITERAL);
    // Independent oracle: node:crypto over the committed bytes.
    expect(verified.payloadDigest).toBe(
      createHash('sha256').update(body).digest('hex'),
    );
  });

  it('accepts the file envelope and the bare artifact identically', () => {
    const ok = vector('REV-OK-01');
    const fromFile = decodeRevocationTransport(JSON.stringify(ok.envelope));
    expect(fromFile.transport).toBe('file');
    expect(fromFile.keyId).toBe(AUTHORITY_A.keyId);
    expect(fromFile.document).toBe(ok.artifact);
    const fromText = decodeRevocationTransport(ok.artifact);
    expect(fromText.transport).toBe('text');
    expect(fromText.keyId).toBeNull();
    const a = parseRevocationDocument(fromFile.document, TRUST_A, {
      keyId: fromFile.keyId,
    });
    const b = parseRevocationDocument(fromText.document, TRUST_A);
    expect(a.payloadDigest).toBe(b.payloadDigest);
  });

  it('refuses a document signed by a key this installation does not trust', () => {
    const revocation = payload({ issuerKeyId: AUTHORITY_B.keyId });
    const artifact = sign(revocation, AUTHORITY_B.privateKeyPkcs8Base64);
    expect(
      rejectionOf(() => parseRevocationDocument(artifact, TRUST_A)).reason,
    ).toBe('signature');
  });

  it('refuses an unknown key hint without scanning the trust list silently', () => {
    const ok = vector('REV-OK-01');
    expect(
      rejectionOf(() =>
        parseRevocationDocument(ok.artifact, TRUST_A, {
          keyId: 'sha256-0000000000000000',
        }),
      ).reason,
    ).toBe('unknown-key');
  });

  it('rejects every committed negative vector with its documented reason', () => {
    const negatives = readdirSync(REVOCATION_VECTORS)
      .filter((name) => name.startsWith('BAD-'))
      .sort()
      .map((name) => loadJson(REVOCATION_VECTORS, name));
    expect(negatives.length).toBeGreaterThanOrEqual(8);
    for (const bad of negatives) {
      const input: string = bad.raw ?? JSON.stringify(bad.envelope);
      const reason = rejectionOf(() => {
        const transport = decodeRevocationTransport(input);
        parseRevocationDocument(transport.document, TRUST_A, {
          keyId: transport.keyId,
        });
      }).reason;
      expect({ id: bad.id, reason }).toEqual({
        id: bad.id,
        reason: bad.expectedReason,
      });
    }
  });

  it('honours the trust-list rotation vectors', () => {
    for (const rotation of [vector('REV-ROT-01'), vector('REV-ROT-02')]) {
      const keys = trusted(...rotation.trustKeys);
      const transport = decodeRevocationTransport(
        JSON.stringify(rotation.envelope),
      );
      if (rotation.expectedResult === 'accepted') {
        const verified = parseRevocationDocument(transport.document, keys, {
          keyId: transport.keyId,
        });
        expect(verified.keyId).toBe(rotation.expectedKeyId);
      } else {
        expect(
          rejectionOf(() =>
            parseRevocationDocument(transport.document, keys, {
              keyId: transport.keyId,
            }),
          ).reason,
        ).toBe(rotation.expectedResult);
      }
    }
  });

  it('rejects tampering even when the armor and base64url stay well formed', () => {
    const original = sign(payload());
    const [, body, signature] = original.split('.') as [string, string, string];
    const tampered = Buffer.from(body, 'base64url')
      .toString('utf8')
      .replace('CONTRACT_TERMINATION', 'NON_PAYMENT');
    const artifact = [
      'VREV1',
      Buffer.from(tampered, 'utf8').toString('base64url'),
      signature,
    ].join('.');
    expect(
      rejectionOf(() => parseRevocationDocument(artifact, TRUST_A)).reason,
    ).toBe('signature');
  });

  it('refuses a license artifact presented as a revocation', () => {
    const license = readJson(VECTORS, 'valid', 'OK-01.json');
    // Structural domain separation: armor prefix first, then the signed kind.
    expect(
      rejectionOf(() => parseRevocationDocument(license.artifact, TRUST_A))
        .reason,
    ).toBe('unsupported-version');
    // A license FILE is not a revocation file: its envelope key is unknown here.
    expect(
      rejectionOf(() =>
        decodeRevocationTransport(
          JSON.stringify({
            format: 'vardena-license',
            fileVersion: 1,
            document: license.artifact,
          }),
        ),
      ).reason,
    ).toBe('malformed');
  });

  it('refuses an envelope with an unexpected field', () => {
    const ok = vector('REV-OK-01');
    expect(
      rejectionOf(() =>
        decodeRevocationTransport(
          JSON.stringify({ ...ok.envelope, authority: 'self' }),
        ),
      ).reason,
    ).toBe('malformed');
  });
});

function readJson(root: string, ...parts: string[]): any {
  const file = join(root, ...parts);
  if (!existsSync(file)) throw new Error(`Missing fixture ${file}`);
  return JSON.parse(readFileSync(file, 'utf8'));
}
