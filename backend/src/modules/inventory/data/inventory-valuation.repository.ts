/**
 * Data access for the valuation projection: states, runs, cost assignment
 * and the bounded recalculation (PDR-05, ADR-0039).
 *
 * **Why recalculation is one key at a time.** A repricing command replays
 * exactly one `(organization, warehouse, item)` key, holding that key's
 * valuation state lock. There is no "recalculate everything" path anywhere
 * in this module, by construction and not by convention: the API takes a
 * single key, the transaction locks a single row, and the replay reads a
 * single key's movements with an explicit upper bound
 * (`RECALCULATION_MOVEMENT_LIMIT`). A request that would exceed the bound is
 * REFUSED with a clear error instead of running an unbounded transaction
 * that could hold locks for minutes.
 *
 * **Why the recalculation takes only the valuation lock.** It never changes
 * a quantity, so it must never block a receipt or an issue on another key —
 * and by taking the LAST lock tier only (see `inventory-locks.ts`) it cannot
 * deadlock with a posting, which takes balance locks first. A concurrent
 * posting on the SAME key serializes behind the state lock, and because a
 * posting inserts its movement row while holding that lock, a replay can
 * never see a half-written history.
 *
 * **Canonical order.** Movements replay in `movement_date, created_at, id`
 * order — the same total order C-54's Kardex uses — so recalculated values
 * always agree with what the Kardex screen shows.
 */

/**
 * The most movements one recalculation will replay. Deliberately explicit:
 * the command is bounded by a number a reviewer can see, not by hope.
 */
export const RECALCULATION_MOVEMENT_LIMIT = 10_000;

export interface ValuationStateFilter {
  organizationId: string;
  branchId?: string | undefined;
  warehouseId?: string | undefined;
  itemId?: string | undefined;
  status?: ValuationStateStatus | undefined;
}

export interface ValuationRunFilter {
  organizationId: string;
  warehouseId?: string | undefined;
  itemId?: string | undefined;
  trigger?: ValuationRunTrigger | undefined;
}

export interface RecalculationInput {
  key: BalanceKey;
  /**
   * The method in force for this item at execution time. It is RECORDED on
   * the run and the state row (what the key is valued under from now on); it
   * is NOT the method the replay applies to history. Each historical movement
   * resolves its own method at its own business date (OD-VAL-14) — see
   * `buildReplayFacts`.
   */
  method: ValuationMethod;
  /**
   * Pre-generated by the caller so the idempotency envelope can reference
   * the run BEFORE the transaction runs — a retried key then replays the
   * same run instead of starting a second one.
   */
  runId: string;
  trigger: ValuationRunTrigger;
  /** Informational only: the whole key always replays (determinism). */
  fromDate: Date | null;
  reason: string | null;
  operation: OperationCreate;
  actorId: string | null;
  at: Date;
}

export interface RecalculationOutput {
  run: InventoryValuationRun;
  state: InventoryValuationState;
}

export interface AssignCostInput {
  movementId: string;
  key: BalanceKey;
  /**
   * The method effective at the priced movement's business date. Recorded on
   * the state; the optional replay still resolves every other movement's
   * method at that movement's own date (OD-VAL-14).
   */
  method: ValuationMethod;
  /** Pre-generated run id; unused when `recalculate` is false. */
  runId: string;
  /** Positive, exact scale-2 amount. */
  totalCost: string;
  reason: string | null;
  /** Explicit second choice: reprice the key now, or leave it stale. */
  recalculate: boolean;
  operation: OperationCreate;
  actorId: string | null;
  at: Date;
}

export interface AssignCostOutput {
  movementId: string;
  state: InventoryValuationState;
  run: InventoryValuationRun | null;
}

@Injectable()
export class InventoryValuationRepository {
  constructor(private readonly prisma: PrismaService) {}

  private client(): Promise<CoreClient> {
    return this.prisma.getClient<CoreClient>();
  }

  private transacting(): Promise<CoreTransactionalClient> {
    return this.prisma.getClient<CoreTransactionalClient>();
  }

  // ---- state reads --------------------------------------------------------

  async findState(key: {
    organizationId: string;
    warehouseId: string;
    itemId: string;
  }): Promise<InventoryValuationState | null> {
    const { inventoryValuationState } = await this.client();
    const row = await inventoryValuationState.findFirst({ where: key });
    return row === null ? null : toStateDomain(row);
  }

  async listStates(params: {
    where: ValuationStateFilter;
    orderBy: OrderBy;
    skip: number;
    take: number;
  }): Promise<{ items: InventoryValuationState[]; total: number }> {
    const { inventoryValuationState } = await this.client();
    const where: ValuationStateWhere = {
      organizationId: params.where.organizationId,
    };
    if (params.where.branchId !== undefined)
      where.branchId = params.where.branchId;
    if (params.where.warehouseId !== undefined)
      where.warehouseId = params.where.warehouseId;
    if (params.where.itemId !== undefined) where.itemId = params.where.itemId;
    if (params.where.status !== undefined) where.status = params.where.status;
    const [rows, total] = await Promise.all([
      inventoryValuationState.findMany({
        where,
        orderBy: params.orderBy,
        skip: params.skip,
        take: params.take,
      }),
      inventoryValuationState.count({ where }),
    ]);
    return { items: rows.map(toStateDomain), total };
  }

  // ---- run reads ----------------------------------------------------------

  async findRunById(id: string): Promise<InventoryValuationRun | null> {
    const { inventoryValuationRun } = await this.client();
    const row = await inventoryValuationRun.findUnique({ where: { id } });
    return row === null ? null : toRunDomain(row);
  }

  async listRuns(params: {
    where: ValuationRunFilter;
    orderBy: OrderBy;
    skip: number;
    take: number;
  }): Promise<{ items: InventoryValuationRun[]; total: number }> {
    const { inventoryValuationRun } = await this.client();
    const where = {
      organizationId: params.where.organizationId,
      ...(params.where.warehouseId === undefined
        ? {}
        : { warehouseId: params.where.warehouseId }),
      ...(params.where.itemId === undefined
        ? {}
        : { itemId: params.where.itemId }),
      ...(params.where.trigger === undefined
        ? {}
        : { trigger: params.where.trigger }),
    };
    const [rows, total] = await Promise.all([
      inventoryValuationRun.findMany({
        where,
        orderBy: params.orderBy,
        skip: params.skip,
        take: params.take,
      }),
      inventoryValuationRun.count({ where }),
    ]);
    return { items: rows.map(toRunDomain), total };
  }

  // ---- backdating ---------------------------------------------------------

  /**
   * Measure what a posting dated `movementDate` would disturb on one key.
   *
   * Read-only and outside any transaction: this is the question the UI asks
   * BEFORE the user commits to anything, and the answer feeds the warning
   * text. The posting path re-derives the verdict under lock, so a race here
   * can only make the UI's preview slightly stale — never a wrong write.
   */
  async assessBackdate(params: {
    organizationId: string;
    warehouseId: string;
    itemId: string;
    movementDate: Date;
  }): Promise<BackdateAssessment> {
    const { inventoryMovement } = await this.client();
    const key = {
      organizationId: params.organizationId,
      warehouseId: params.warehouseId,
      itemId: params.itemId,
    };
    const aggregate = await inventoryMovement.aggregate({
      where: key,
      _sum: { baseQuantity: true },
      _max: { movementDate: true },
    });
    const latestMovementDate = aggregate._max.movementDate;
    const laterWhere = {
      ...key,
      // Strictly later: a movement at the same instant is not "after" the
      // proposed one — the canonical order breaks that tie, not the clock.
      movementDate: { gt: params.movementDate },
    };
    const [affectedMovements, affectedValuedMovements, state] =
      await Promise.all([
        inventoryMovement.count({ where: laterWhere }),
        inventoryMovement.count({
          where: {
            ...laterWhere,
            valuationStatus: { in: ['valued', 'provisional'] },
          },
        }),
        this.findState(key),
      ]);
    return {
      backdated:
        latestMovementDate !== null &&
        params.movementDate.getTime() < latestMovementDate.getTime(),
      movementDate: params.movementDate,
      latestMovementDate,
      affectedMovements,
      affectedValuedMovements,
      alreadyStale: state?.status === 'stale',
    };
  }

  /**
   * Runs on ONE key executed strictly after an instant — the OD-RVP-02
   * latest-run guard: a run with any newer run on its key may not be
   * reversed, because reversing out of order corrupts the replay chain.
   */
  async listRunsForKeyAfter(params: {
    organizationId: string;
    warehouseId: string;
    itemId: string;
    executedAfter: Date;
  }): Promise<InventoryValuationRun[]> {
    const { inventoryValuationRun } = await this.client();
    const rows = await inventoryValuationRun.findMany({
      where: {
        organizationId: params.organizationId,
        warehouseId: params.warehouseId,
        itemId: params.itemId,
        executedAt: { gt: params.executedAfter },
      },
      orderBy: [{ executedAt: 'asc' }],
      skip: 0,
      take: 20,
    });
    return rows.map(toRunDomain);
  }

  // ---- commands -----------------------------------------------------------

  /**
   * Replay one key deterministically and persist the result.
   *
   * Everything happens in ONE transaction: the movements' valuation columns,
   * the state row, the run record and the idempotency row commit together,
   * so a failed replay leaves no trace and a partially repriced key is
   * impossible.
   */
  async recalculateKey(
    input: RecalculationInput,
  ): Promise<RecalculationOutput> {
    const client = await this.transacting();
    return client.$transaction((tx) => this.recalculateKeyWithin(tx, input));
  }

  /**
   * The same replay, executed inside a transaction the CALLER owns.
   *
   * This is the composable half of `recalculateKey`: identical arithmetic
   * (one `applyReplay`, one state row, one run record, one idempotency row),
   * but joined to an outer `BEGIN … COMMIT` so a command that both moves
   * stock and reprices the affected keys commits — or rolls back — as one
   * unit (C-58 finalize/edit with explicit `repricing: "recalculate"`).
   *
   * A failure here therefore aborts the caller's transaction too, which is
   * the point: no warehouse fact may survive a valuation replay that did not
   * happen. Callers that must keep the quantity fact regardless of the
   * valuation outcome keep using `recalculateKey`, which owns its own
   * transaction.
   */
  async recalculateKeyWithin(
    tx: CoreTxClient,
    input: RecalculationInput,
  ): Promise<RecalculationOutput> {
    const { state } = await lockValuationStateRow(
      tx,
      input.key,
      input.method,
      input.actorId,
    );
    const applied = await applyReplay(tx, {
      state,
      runId: input.runId,
      key: input.key,
      method: input.method,
      trigger: input.trigger,
      fromDate: input.fromDate,
      reason: input.reason,
      operationKey: input.operation.operationKey,
      at: input.at,
      actorId: input.actorId,
    });
    await insertOperationRow(tx, input.operation);
    return { run: applied.run, state: applied.state };
  }

  /**
   * The batch flavor of {@link recalculateKeyWithin} (C-59E Periodic
   * Pricing): identical arithmetic — lock, whole-key replay, state write —
   * but the idempotency unit is the BATCH, so the caller inserts ONE
   * operation row for the whole run and this method writes none. The caller
   * (the pricing service) pre-locks every key's state row in ascending order
   * before calling this per key, so the re-entrant single-key lock inside
   * never waits and the module's single multi-key lock discipline is upheld.
   */
  async recalculateKeyWithinBatch(
    tx: CoreTxClient,
    input: Omit<RecalculationInput, 'operation'> & { operationKey: string },
  ): Promise<RecalculationOutput> {
    const { state } = await lockValuationStateRow(
      tx,
      input.key,
      input.method,
      input.actorId,
    );
    const applied = await applyReplay(tx, {
      state,
      runId: input.runId,
      key: input.key,
      method: input.method,
      trigger: input.trigger,
      fromDate: input.fromDate,
      reason: input.reason,
      operationKey: input.operationKey,
      at: input.at,
      actorId: input.actorId,
    });
    return { run: applied.run, state: applied.state };
  }

  /**
   * The REVERSE of one per-key run, executed inside a transaction the CALLER
   * owns (C-59E+, OD-RVP-04…06). Four steps, one transaction, one key:
   *
   *   1. lock the key's valuation-state row (the last lock tier),
   *   2. set every movement the run valued back to `unvalued`
   *      (OD-RVP-06 — never a quantity column),
   *   3. fold the surviving facts into the pre-run POSITION with the pure
   *      preserve-fold (`valuation-compensation.ts`) — nothing is repriced,
   *   4. record the compensating `inventory_valuation_runs` row and mark the
   *      state STALE ("requiring repricing"), pointing
   *      `last_recalculation_id` at the compensating run.
   *
   * The caller (the pricing service) owns the OD-RVP-02/03/07 guards: this
   * method performs the write once the decision to reverse has been made.
   */
  async reverseRunWithin(
    tx: CoreTxClient,
    input: {
      key: BalanceKey;
      method: ValuationMethod;
      /** The per-key run being reversed. */
      originalRunId: string;
      /** Pre-generated compensating run id. */
      compensatingRunId: string;
      reason: string | null;
      at: Date;
      actorId: string | null;
    },
  ): Promise<{
    run: InventoryValuationRun;
    state: InventoryValuationState;
    movementsUnvalued: number;
  }> {
    const { state } = await lockValuationStateRow(
      tx,
      input.key,
      input.method,
      input.actorId,
    );
    const rows = await readKeyMovements(tx, input.key);
    const reversed = rows.filter(
      (row) => row.valuationRunId === input.originalRunId,
    );

    // Fold the SURVIVING facts into the pre-run position, honestly, without
    // repricing anything. `rows` is the PRE-update snapshot by design (the
    // movements are un-valued only further below), so the fold input MUST be
    // derived through `toCompensationFacts` with the ORIGINAL run id: that is
    // what turns the rows this transaction un-values into the `null`-value
    // facts they are from now on. Folding the raw snapshot instead would keep
    // counting the erased values and produce the post-run position — the
    // stale-snapshot defect this guards against (C-59 correction sprint,
    // axis 1).
    const position = foldPreservedPosition(
      toCompensationFacts(
        rows.map((row) => ({
          movementType: toMovementType(row.id, row.movementType),
          baseQuantity: decimalToString(row.baseQuantity),
          totalCost:
            row.totalCost === null ? null : decimalToString(row.totalCost),
          valuationSource: toSource(row.id, row.valuationSource),
          valuationRunId: row.valuationRunId,
        })),
        input.originalRunId,
      ),
    );

    const create: ValuationRunCreate = {
      id: input.compensatingRunId,
      organizationId: input.key.organizationId,
      branchId: input.key.branchId,
      warehouseId: input.key.warehouseId,
      itemId: input.key.itemId,
      method: input.method,
      trigger: 'reverse_pricing',
      fromDate: null,
      movementsExamined: rows.length,
      movementsRevalued: reversed.length,
      resultingValuedQuantity: position.valuedQuantity,
      resultingUncostedQuantity: position.uncostedQuantity,
      resultingTotalValue: position.totalValue,
      // OD-RVP-06: the key explicitly requires repricing after a reverse.
      resultingStatus: 'stale',
      operationKey: `reverse:${input.originalRunId}`,
      reason: input.reason,
      executedAt: input.at,
      createdAt: input.at,
      updatedAt: input.at,
      createdBy: input.actorId,
    };
    // The compensating per-key run row is created BEFORE the movements are
    // stamped with its id: `inventory_movements.valuation_run_id` carries a
    // real FK into `inventory_valuation_runs` (`fk_inventory_movements_valuation_run`),
    // so writing the stamp first would violate the constraint inside this
    // same transaction. Same transaction, same committed state — only the
    // statement order inside it changed (C-59 correction sprint: the reverse
    // path had never run against a real database before the live suite).
    const run = toRunDomain(
      await tx.inventoryValuationRun.create({ data: create }),
    );

    for (const row of reversed) {
      await tx.inventoryMovement.update({
        where: { id: row.id },
        data: {
          totalCost: null,
          valuationStatus: 'unvalued',
          valuationSource: null,
          valuedAt: null,
          valuationRunId: input.compensatingRunId,
          updatedAt: input.at,
          updatedBy: input.actorId,
        },
      });
    }

    await writeValuationState(tx, {
      state,
      position,
      method: input.method,
      marksStale: true,
      at: input.at,
      actorId: input.actorId,
      recalculationId: input.compensatingRunId,
      clearStale: false,
    });

    return {
      run,
      state: await reloadState(tx, state),
      movementsUnvalued: reversed.length,
    };
  }

  /**
   * Attach a cost to a movement that was posted without one, then either
   * reprice the key (explicit choice) or leave it marked inconsistent.
   *
   * Assigning a cost is the "late price" half of cost-optional operations
   * (OD-VAL-06): the warehouse already recorded the quantity, accounting
   * supplies the value afterwards. It is only ever an ADDITION — overwriting
   * a cost that already exists is refused (`CostAlreadyAssignedError`),
   * because that would silently rewrite a figure someone may already have
   * reported on. Correcting a wrong cost is a reversal, exactly as it is for
   * a wrong quantity.
   *
   * The repricing question is asked again here, and for the same reason it
   * is asked on a backdated posting: a cost that arrives after later
   * movements were already valued changes their values too, and only the
   * operator may decide whether that happens now (OD-VAL-11).
   */
  async assignCost(input: AssignCostInput): Promise<AssignCostOutput> {
    const client = await this.transacting();
    return client.$transaction(async (tx) => {
      const movement = await lockMovementRow(tx, input.movementId);
      if (movement === null) {
        throw new Error(`Movement "${input.movementId}" does not exist.`);
      }
      if (movement.valuationStatus !== 'unvalued') {
        throw new CostAlreadyAssignedError(input.movementId);
      }
      const { state } = await lockValuationStateRow(
        tx,
        input.key,
        input.method,
        input.actorId,
      );
      await tx.inventoryMovement.update({
        where: { id: input.movementId },
        data: {
          totalCost: input.totalCost,
          valuationStatus: 'valued',
          valuationSource: 'entered',
          valuedAt: input.at,
          valuationRunId: null,
          updatedAt: input.at,
          updatedBy: input.actorId,
        },
      });

      if (!input.recalculate) {
        // The stored position no longer matches the facts — say so, and
        // leave the repair to an explicit command (OD-VAL-11). This is the
        // honest half of "do not recalculate": the number stays visible and
        // stays labelled inconsistent.
        await writeValuationState(tx, {
          state,
          position: positionOf(state),
          method: input.method,
          marksStale: true,
          at: input.at,
          actorId: input.actorId,
        });
        await insertOperationRow(tx, input.operation);
        return {
          movementId: input.movementId,
          state: await reloadState(tx, state),
          run: null,
        };
      }

      const applied = await applyReplay(tx, {
        state,
        runId: input.runId,
        key: input.key,
        method: input.method,
        trigger: 'cost_assignment',
        fromDate: null,
        reason: input.reason,
        operationKey: input.operation.operationKey,
        at: input.at,
        actorId: input.actorId,
      });
      await insertOperationRow(tx, input.operation);
      return {
        movementId: input.movementId,
        state: applied.state,
        run: applied.run,
      };
    });
  }
}

// ---- Internal helpers ----

/**
 * One key's movements in the canonical ledger order, with an explicit upper
 * bound. The `+ 1` read is how the bound is DETECTED rather than silently
 * truncated: a key with more history than the command can replay is refused.
 */
export async function readKeyMovements(
  tx: CoreTxClient,
  key: BalanceKey,
): Promise<MovementRow[]> {
  const rows = await tx.inventoryMovement.findMany({
    where: {
      organizationId: key.organizationId,
      warehouseId: key.warehouseId,
      itemId: key.itemId,
    },
    orderBy: [{ movementDate: 'asc' }, { createdAt: 'asc' }, { id: 'asc' }],
    skip: 0,
    take: RECALCULATION_MOVEMENT_LIMIT + 1,
  });
  if (rows.length > RECALCULATION_MOVEMENT_LIMIT) {
    throw new RecalculationTooLargeError(RECALCULATION_MOVEMENT_LIMIT);
  }
  return rows;
}

function toFact(row: MovementRow, method: ValuationMethod): ReplayFact {
  return toReplayFact(
    {
      id: row.id,
      movementType: toMovementType(row.id, row.movementType),
      baseQuantity: decimalToString(row.baseQuantity),
      totalCost: row.totalCost === null ? null : decimalToString(row.totalCost),
      valuationStatus: toMovementStatus(row.id, row.valuationStatus),
      valuationSource: toSource(row.id, row.valuationSource),
    },
    method,
  );
}

/**
 * The valuation-method versions the replay can actually consume: those in
 * force at one or more of the DISTINCT movement dates being replayed.
 *
 * Read INSIDE the replay transaction, so the resolution cannot race a
 * concurrent configuration change.
 *
 * **Why it is bounded by the right quantity.** The question a replay asks is
 * not "what does this item's configuration history look like?" but "which
 * version is in force at each date I am replaying?". So the read asks
 * exactly that, as one OR branch per distinct date:
 *
 * ```sql
 * WHERE organization_id = $1 AND item_id = $2 AND (
 *     (valid_from <= d1 AND (valid_to IS NULL OR valid_to > d1))
 *  OR (valid_from <= d2 AND (valid_to IS NULL OR valid_to > d2)) ... )
 * ```
 *
 * Every row that comes back is in force for at least one replayed movement,
 * and windows cannot overlap (`planNewVersion` rejects that on write), so at
 * most ONE row comes back per distinct date. The result is therefore bounded
 * by the number of distinct movement dates — which the movement limit
 * already bounds — and NOT by how densely the item has been reconfigured.
 *
 * An earlier version of this function filtered by the replay HORIZON
 * (`first..last movement date`) and capped the result at the movement limit.
 * That cap was wrong: the horizon returns every version *intersecting* the
 * span, a count driven by configuration density, so two movements a year
 * apart could drag in a year of monthly versions and a sparse replay could
 * be refused for a limit that is about movements. Selecting per date removes
 * the mismatch instead of raising the cap.
 *
 * **Completeness.** For any replayed date `d`, every version covering `d`
 * satisfies `d`'s branch and is returned, so resolving `d` against this
 * result is identical to resolving it against the item's whole history —
 * including when the answer is "no version covers it", which keeps the
 * code-defined default. Future configuration (starts after every replayed
 * date) and expired configuration (ended before all of them) are excluded
 * because they are in force for no replayed movement, not as special cases.
 * Asserted in `domain/valuation-method.spec.ts`.
 *
 * **Ambiguity is checked per date, not by counting rows.** Every instant is
 * examined on its own: if two versions are in force at one movement date the
 * replay fails closed (`AmbiguousValuationMethodError`). A global "more rows
 * than dates?" comparison would be unsound — two versions on one date and
 * none on another returns exactly as many rows as there are dates — which is
 * why the count check that used to live here is gone.
 *
 * The read still transfers at most one row more than there are dates, and
 * that cannot hide an overlap: the query only returns rows that cover some
 * date, so if every fetched date looked unambiguous while an overlap existed
 * beyond the cut-off, the rows before it would have to cover the remaining
 * dates more than once — which the same per-date check would have caught.
 */
export async function readMethodVersions(
  tx: CoreTxClient,
  key: BalanceKey,
  movementDates: readonly Date[],
): Promise<ItemValuationMethodVersion[]> {
  const instants = distinctInstants(movementDates);
  // No movements, nothing to resolve: an empty key reads no configuration.
  if (instants.length === 0) return [];
  const rows = await tx.itemValuationMethod.findMany({
    where: {
      organizationId: key.organizationId,
      itemId: key.itemId,
      OR: instants.map((instant) => ({
        validFrom: { lte: instant },
        OR: [{ validTo: null }, { validTo: { gt: instant } }],
      })),
    },
    orderBy: [{ validFrom: 'asc' }],
    skip: 0,
    take: instants.length + 1,
  });
  const versions = rows.map((row) => {
    if (!isValuationMethod(row.method)) {
      throw new Error(
        `Stored valuation method version "${row.id}" has an unknown method "${row.method}".`,
      );
    }
    return {
      id: row.id,
      organizationId: row.organizationId,
      itemId: row.itemId,
      method: row.method,
      validFrom: row.validFrom,
      validTo: row.validTo,
      note: row.note,
      createdAt: row.createdAt,
      updatedAt: row.updatedAt,
    };
  });
  const ambiguous = findAmbiguousInstant(versions, instants);
  if (ambiguous !== null) {
    throw new AmbiguousValuationMethodError(
      key.itemId,
      ambiguous.instant,
      ambiguous.versionIds,
    );
  }
  return versions;
}

/**
 * Pair every movement with the method that was effective for it AT ITS OWN
 * BUSINESS DATE (OD-VAL-14). This is the whole point of the effective-dated
 * configuration: a 1404 movement must not be revalued with a method that only
 * became effective in 1405, and vice versa.
 */
export function buildReplayFacts(
  rows: readonly MovementRow[],
  versions: readonly ItemValuationMethodVersion[],
): ReplayFact[] {
  return rows.map((row) =>
    toFact(row, resolveValuationMethodAt(versions, row.movementDate).method),
  );
}

/**
 * Replay one key and write everything the replay implies: the changed
 * movement rows, the run record, and the state.
 *
 * The replay itself is pure and runs to completion BEFORE anything is
 * written, so the run row can be inserted with the real "how many rows
 * changed" count — reporting work that happened, never work that was
 * planned. The caller owns the transaction and the state lock.
 */
async function applyReplay(
  tx: CoreTxClient,
  input: {
    state: InventoryValuationState;
    runId: string;
    key: BalanceKey;
    method: ValuationMethod;
    trigger: ValuationRunTrigger;
    fromDate: Date | null;
    reason: string | null;
    operationKey: string;
    at: Date;
    actorId: string | null;
  },
): Promise<{ run: InventoryValuationRun; state: InventoryValuationState }> {
  const rows = await readKeyMovements(tx, input.key);
  const versions = await readMethodVersions(
    tx,
    input.key,
    rows.map((row) => row.movementDate),
  );
  // One strategy lookup PER MOVEMENT at that movement's business date — never
  // one method for the whole history (OD-VAL-14). A period configured with a
  // method this build cannot execute fails the replay closed rather than
  // silently revaluing it with the method in force today.
  const result = replay(buildReplayFacts(rows, versions));

  const changes = rows.flatMap((row, index) => {
    const next = result.movements[index];
    if (next === undefined) return [];
    const before = {
      status: toMovementStatus(row.id, row.valuationStatus),
      totalCost: row.totalCost === null ? null : decimalToString(row.totalCost),
      source: toSource(row.id, row.valuationSource),
    };
    return valuationChanged(before, next.valuation)
      ? [{ id: row.id, valuation: next.valuation }]
      : [];
  });

  const runId = input.runId;
  const create: ValuationRunCreate = {
    id: runId,
    organizationId: input.key.organizationId,
    branchId: input.key.branchId,
    warehouseId: input.key.warehouseId,
    itemId: input.key.itemId,
    method: input.method,
    trigger: input.trigger,
    fromDate: input.fromDate,
    movementsExamined: rows.length,
    movementsRevalued: changes.length,
    resultingValuedQuantity: result.position.valuedQuantity,
    resultingUncostedQuantity: result.position.uncostedQuantity,
    resultingTotalValue: result.position.totalValue,
    resultingStatus: resolveValuationStatus({
      uncostedQuantity: result.position.uncostedQuantity,
      staleSince: result.provisional ? input.at : null,
    }),
    operationKey: input.operationKey,
    reason: input.reason,
    executedAt: input.at,
    createdAt: input.at,
    updatedAt: input.at,
    createdBy: input.actorId,
  };
  const run = toRunDomain(
    await tx.inventoryValuationRun.create({ data: create }),
  );

  for (const change of changes) {
    await tx.inventoryMovement.update({
      where: { id: change.id },
      data: {
        totalCost: change.valuation.totalCost,
        valuationStatus: change.valuation.status,
        valuationSource: change.valuation.source,
        valuedAt: change.valuation.status === 'unvalued' ? null : input.at,
        valuationRunId: runId,
        updatedAt: input.at,
        updatedBy: input.actorId,
      },
    });
  }

  await writeValuationState(tx, {
    state: input.state,
    position: result.position,
    method: input.method,
    // A replay re-establishes consistency; it can only stay inconsistent if
    // the facts themselves are still provisional (e.g. stock whose cost
    // nobody has supplied was already issued).
    marksStale: result.provisional,
    at: input.at,
    actorId: input.actorId,
    recalculationId: runId,
    clearStale: true,
  });

  return { run, state: await reloadState(tx, input.state) };
}

async function reloadState(
  tx: CoreTxClient,
  state: InventoryValuationState,
): Promise<InventoryValuationState> {
  const row = await tx.inventoryValuationState.findUnique({
    where: { id: state.id },
  });
  return row === null ? state : toStateDomain(row);
}

function toMovementType(id: string, value: string): MovementType {
  if (!isMovementType(value)) {
    throw new Error(`Stored movement "${id}" has an unknown type "${value}".`);
  }
  return value;
}

function toMovementStatus(id: string, value: string): MovementValuationStatus {
  if (!(MOVEMENT_VALUATION_STATUSES as readonly string[]).includes(value)) {
    throw new Error(
      `Stored movement "${id}" has an unknown valuation status "${value}".`,
    );
  }
  return value as MovementValuationStatus;
}

function toSource(id: string, value: string | null): ValuationSource | null {
  if (value === null) return null;
  if (!(VALUATION_SOURCES as readonly string[]).includes(value)) {
    throw new Error(
      `Stored movement "${id}" has an unknown valuation source "${value}".`,
    );
  }
  return value as ValuationSource;
}

function toStateDomain(row: ValuationStateRow): InventoryValuationState {
  if (!isValuationMethod(row.method)) {
    throw new Error(
      `Stored valuation state "${row.id}" has an unknown method "${row.method}".`,
    );
  }
  if (!(VALUATION_STATE_STATUSES as readonly string[]).includes(row.status)) {
    throw new Error(
      `Stored valuation state "${row.id}" has an unknown status "${row.status}".`,
    );
  }
  return {
    id: row.id,
    organizationId: row.organizationId,
    branchId: row.branchId,
    warehouseId: row.warehouseId,
    itemId: row.itemId,
    method: row.method,
    valuedQuantity: decimalToString(row.valuedQuantity),
    uncostedQuantity: decimalToString(row.uncostedQuantity),
    totalValue: decimalToString(row.totalValue),
    status: row.status as ValuationStateStatus,
    staleSince: row.staleSince,
    lastValuedAt: row.lastValuedAt,
    lastRecalculationId: row.lastRecalculationId,
    createdAt: row.createdAt,
    updatedAt: row.updatedAt,
  };
}

function toRunDomain(row: ValuationRunRow): InventoryValuationRun {
  if (!isValuationMethod(row.method)) {
    throw new Error(
      `Stored valuation run "${row.id}" has an unknown method "${row.method}".`,
    );
  }
  if (!(VALUATION_RUN_TRIGGERS as readonly string[]).includes(row.trigger)) {
    throw new Error(
      `Stored valuation run "${row.id}" has an unknown trigger "${row.trigger}".`,
    );
  }
  if (
    !(VALUATION_STATE_STATUSES as readonly string[]).includes(
      row.resultingStatus,
    )
  ) {
    throw new Error(
      `Stored valuation run "${row.id}" has an unknown resulting status "${row.resultingStatus}".`,
    );
  }
  return {
    id: row.id,
    organizationId: row.organizationId,
    branchId: row.branchId,
    warehouseId: row.warehouseId,
    itemId: row.itemId,
    method: row.method,
    trigger: row.trigger as ValuationRunTrigger,
    fromDate: row.fromDate,
    movementsExamined: row.movementsExamined,
    movementsRevalued: row.movementsRevalued,
    resultingValuedQuantity: decimalToString(row.resultingValuedQuantity),
    resultingUncostedQuantity: decimalToString(row.resultingUncostedQuantity),
    resultingTotalValue: decimalToString(row.resultingTotalValue),
    resultingStatus: row.resultingStatus as ValuationStateStatus,
    operationKey: row.operationKey,
    reason: row.reason,
    executedAt: row.executedAt,
    createdAt: row.createdAt,
    updatedAt: row.updatedAt,
  };
}
